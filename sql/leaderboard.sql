-- 在 Supabase Dashboard → SQL Editor 中执行本文件。

create table if not exists public.steel_runs (
  id bigint generated by default as identity primary key,
  run_id uuid not null unique,
  player_id text not null,
  nickname text not null,
  mode text not null check (mode in ('melee', 'lastStand', 'naval', 'navalLastStand')),
  difficulty text not null check (difficulty in ('easy', 'normal', 'hard', 'endless')),
  map_id text,
  result text not null default 'loss' check (result in ('win', 'loss', 'settled')),
  score integer not null default 0 check (score >= 0),
  yellow_xp integer not null default 0 check (yellow_xp >= 0),
  kills integer not null default 0 check (kills >= 0),
  losses integer not null default 0 check (losses >= 0),
  duration_sec integer not null default 0 check (duration_sec >= 0),
  wave integer not null default 0 check (wave >= 0),
  hold_sec integer not null default 0 check (hold_sec >= 0),
  ships_sunk integer not null default 0 check (ships_sunk >= 0),
  boss_kills integer not null default 0 check (boss_kills >= 0),
  client_version text,
  created_at timestamptz not null default now(),
  constraint steel_runs_player_len check (char_length(player_id) between 8 and 80),
  constraint steel_runs_nickname_len check (char_length(nickname) between 1 and 24)
);

create index if not exists steel_runs_mode_rank_idx
  on public.steel_runs (mode, difficulty, yellow_xp desc, score desc, kills desc, created_at asc);

create index if not exists steel_runs_stand_rank_idx
  on public.steel_runs (mode, difficulty, wave desc, hold_sec desc, kills desc, score desc, created_at asc);

create index if not exists steel_runs_player_idx
  on public.steel_runs (player_id, created_at desc);

-- 只允许服务端 API 使用 service_role 访问；浏览器不直接读写。
alter table public.steel_runs enable row level security;
